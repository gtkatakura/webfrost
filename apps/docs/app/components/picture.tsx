import { cn } from "@/lib/cn";
import { useState } from "react";

/** What vite-imagetools returns for an import ending in `&as=picture`. */
export interface PictureSource {
  sources: Record<string, string>;
  img: { src: string; w: number; h: number };
}

/** Combine imports made with different settings per format; the fallback <img> is the last one's. */
export function mergePictures(...pictures: PictureSource[]): PictureSource {
  const last = pictures[pictures.length - 1];
  if (!last) throw new Error("mergePictures needs at least one picture");
  return { sources: Object.assign({}, ...pictures.map((x) => x.sources)), img: last.img };
}

const MIME: Record<string, string> = {
  avif: "image/avif",
  webp: "image/webp",
  jpg: "image/jpeg",
  jpeg: "image/jpeg",
  png: "image/png",
};

/** Best first: the browser takes the first <source> whose type it understands. */
const ORDER = ["avif", "webp", "png", "jpg", "jpeg"];

function sourcesOf(picture: PictureSource, sizes: string, media?: string) {
  return Object.entries(picture.sources)
    .sort(([a], [b]) => ORDER.indexOf(a) - ORDER.indexOf(b))
    .map(([format, srcSet]) => (
      <source
        key={`${media ?? "all"}-${format}`}
        type={MIME[format]}
        srcSet={srcSet}
        sizes={sizes}
        media={media}
      />
    ));
}

/**
 * A responsive image in the spirit of next/image, done at build time:
 * - every width and format is generated by vite-imagetools; the browser picks by screen size and support;
 * - `narrow` is a different crop for small screens (art direction), used below `narrowBelow` px;
 * - width and height are set, so the page does not shift when the image arrives;
 * - `placeholder` is a tiny blurred version shown until the real image has loaded.
 */
export function Picture({
  picture,
  narrow,
  narrowBelow = 640,
  sizes,
  alt,
  placeholder,
  priority = false,
  className,
}: {
  picture: PictureSource;
  narrow?: PictureSource;
  narrowBelow?: number;
  sizes: string;
  alt: string;
  placeholder?: string;
  /** Above the fold: load at once, with high priority. Otherwise lazy. */
  priority?: boolean;
  className?: string;
}) {
  const [loaded, setLoaded] = useState(false);
  return (
    <div className={cn("relative overflow-hidden", className)}>
      {placeholder && (
        <img
          src={placeholder}
          alt=""
          aria-hidden="true"
          className={cn(
            "absolute inset-0 size-full scale-110 object-cover blur-xl transition-opacity duration-500",
            loaded && "opacity-0",
          )}
        />
      )}
      <picture>
        {narrow && sourcesOf(narrow, sizes, `(max-width: ${narrowBelow - 1}px)`)}
        {sourcesOf(picture, sizes)}
        <img
          src={picture.img.src}
          width={picture.img.w}
          height={picture.img.h}
          alt={alt}
          sizes={sizes}
          loading={priority ? "eager" : "lazy"}
          fetchPriority={priority ? "high" : "auto"}
          decoding="async"
          onLoad={() => setLoaded(true)}
          // Already in the cache when React hydrates: onLoad will not fire again.
          ref={(el) => {
            if (el?.complete) setLoaded(true);
          }}
          className={cn(
            "relative block h-auto w-full transition-opacity duration-500",
            !loaded && placeholder && "opacity-0",
          )}
        />
      </picture>
    </div>
  );
}
