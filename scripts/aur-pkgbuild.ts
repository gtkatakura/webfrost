/**
 * Write the AUR package webfrost-bin (PKGBUILD and .SRCINFO) for a release of WebFrost.
 *
 *   bun scripts/aur-pkgbuild.ts --version 1.2.3 --checksums release/checksums.txt --out aur/
 *
 * The package installs the prebuilt binary from the GitHub release, x86_64 or aarch64, with the
 * libraries the browser needs as dependencies. The hashes come from the release's checksums.txt.
 * .SRCINFO is written here, in the format `makepkg --printsrcinfo` prints, so the release runner
 * needs no Arch tools.
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { parseChecksums } from "./homebrew-formula";

const REPO = process.env.GITHUB_REPOSITORY ?? "gtkatakura/webfrost";
const PKGDESC =
  "Self-hosted web archiver: WARC, PDF, screenshot, readable text, self-contained HTML and video from one visit";
const DEPENDS = [
  "glib2",
  "nss",
  "nspr",
  "atk",
  "at-spi2-core",
  "libcups",
  "libxkbcommon",
  "libxcomposite",
  "libxdamage",
  "libxfixes",
  "libxrandr",
  "mesa",
  "pango",
  "cairo",
  "alsa-lib",
  "dbus",
];
const OPTDEPENDS = [
  "yt-dlp: archive video and audio",
  "ffmpeg: archive video and audio",
  "ttf-liberation: fonts for screenshots and PDFs",
];
const ARCHES = [
  { arch: "x86_64", target: "linux-x64" },
  { arch: "aarch64", target: "linux-arm64" },
] as const;

export function aurPackage(
  version: string,
  checksums: Map<string, string>,
  repo = REPO,
): { pkgbuild: string; srcinfo: string } {
  const sources = ARCHES.map(({ arch, target }) => {
    const file = `webfrost-${target}.tar.gz`;
    const sha = checksums.get(file);
    if (!sha) throw new Error(`checksums.txt has no entry for ${file}`);
    const name = `webfrost-${version}-${arch}.tar.gz`;
    return {
      arch,
      sha,
      source: `${name}::https://github.com/${repo}/releases/download/v${version}/${file}`,
    };
  });
  const q = (items: readonly string[]) => items.map((i) => `'${i}'`).join(" ");
  const pkgbuild = `# Maintainer: gtkatakura <gtkatakura@users.noreply.github.com>
# Generated by the release workflow of ${repo}. Do not edit it by hand.
pkgname=webfrost-bin
pkgver=${version}
pkgrel=1
pkgdesc="${PKGDESC}"
arch=(${q(ARCHES.map((a) => a.arch))})
url="https://webfrost.dev"
license=('MIT')
provides=('webfrost')
conflicts=('webfrost')
depends=(${q(DEPENDS)})
optdepends=(${q(OPTDEPENDS)})
# A binary compiled by Bun keeps the program at the end of the file: strip would cut it off.
options=('!strip')
${sources.map((s) => `source_${s.arch}=("${s.source}")`).join("\n")}
${sources.map((s) => `sha256sums_${s.arch}=('${s.sha}')`).join("\n")}

package() {
  install -Dm755 webfrost "$pkgdir/usr/bin/webfrost"
  install -Dm644 LICENSE "$pkgdir/usr/share/licenses/$pkgname/LICENSE"
}
`;
  const lines = [
    "pkgbase = webfrost-bin",
    `\tpkgdesc = ${PKGDESC}`,
    `\tpkgver = ${version}`,
    "\tpkgrel = 1",
    "\turl = https://webfrost.dev",
    ...ARCHES.map((a) => `\tarch = ${a.arch}`),
    "\tlicense = MIT",
    ...DEPENDS.map((d) => `\tdepends = ${d}`),
    ...OPTDEPENDS.map((d) => `\toptdepends = ${d}`),
    "\tprovides = webfrost",
    "\tconflicts = webfrost",
    "\toptions = !strip",
    ...sources.flatMap((s) => [
      `\tsource_${s.arch} = ${s.source}`,
      `\tsha256sums_${s.arch} = ${s.sha}`,
    ]),
    "",
    "pkgname = webfrost-bin",
    "",
  ];
  return { pkgbuild, srcinfo: lines.join("\n") };
}

if (import.meta.main) {
  const argv = process.argv.slice(2);
  const arg = (name: string) => {
    const i = argv.indexOf(`--${name}`);
    const value = i === -1 ? undefined : argv[i + 1];
    if (!value) throw new Error(`--${name} is required`);
    return value;
  };
  const { pkgbuild, srcinfo } = aurPackage(
    arg("version"),
    parseChecksums(readFileSync(arg("checksums"), "utf8")),
  );
  const out = arg("out");
  mkdirSync(out, { recursive: true });
  writeFileSync(join(out, "PKGBUILD"), pkgbuild);
  writeFileSync(join(out, ".SRCINFO"), srcinfo);
  console.log(pkgbuild);
}
