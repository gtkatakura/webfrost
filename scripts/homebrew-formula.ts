/**
 * Print the Homebrew formula for a release of WebFrost.
 *
 *   bun scripts/homebrew-formula.ts --version 1.2.3 --checksums release/checksums.txt > webfrost.rb
 *
 * The formula installs the prebuilt binary from the GitHub release (no build step), one
 * archive per OS and CPU. The hashes come from the release's checksums.txt, which the
 * release workflow produces; a missing archive is an error rather than an empty hash.
 */
import { readFileSync } from "node:fs";

const REPO = process.env.GITHUB_REPOSITORY ?? "gtkatakura/webfrost";

export function parseChecksums(text: string): Map<string, string> {
  const hashes = new Map<string, string>();
  for (const line of text.split("\n")) {
    const match = /^([0-9a-f]{64})\s+\*?(\S+)$/.exec(line.trim());
    if (match?.[1] && match[2]) hashes.set(match[2], match[1]);
  }
  return hashes;
}

export function formula(version: string, checksums: Map<string, string>, repo = REPO): string {
  const block = (target: string): string => {
    const file = `webfrost-${target}.tar.gz`;
    const sha = checksums.get(file);
    if (!sha) throw new Error(`checksums.txt has no entry for ${file}`);
    return `url "https://github.com/${repo}/releases/download/v${version}/${file}"\n      sha256 "${sha}"`;
  };
  return `# This file is generated by the release workflow of ${repo}. Do not edit it by hand.
class Webfrost < Formula
  desc "Self-hosted web archiver: saves pages as WARC, PDF, screenshot, text and more"
  homepage "https://webfrost.dev"
  version "${version}"
  license "MIT"

  on_macos do
    on_arm do
      ${block("darwin-arm64")}
    end
    on_intel do
      ${block("darwin-x64")}
    end
  end

  on_linux do
    on_arm do
      ${block("linux-arm64")}
    end
    on_intel do
      ${block("linux-x64")}
    end
  end

  def install
    bin.install "webfrost"
  end

  def caveats
    <<~EOS
      WebFrost archives pages with a headless Chromium. If you have none, install one with:
        webfrost setup

      Video and audio need yt-dlp and ffmpeg, which are optional:
        brew install yt-dlp ffmpeg

      Start the server, web UI and scheduler on http://localhost:3000:
        webfrost serve

      Check what is missing with:
        webfrost doctor
    EOS
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/webfrost --version")
  end
end
`;
}

if (import.meta.main) {
  const argv = process.argv.slice(2);
  const arg = (name: string): string | undefined => {
    const i = argv.indexOf(`--${name}`);
    return i === -1 ? undefined : argv[i + 1];
  };
  const version = arg("version")?.replace(/^v/, "");
  const checksumsFile = arg("checksums");
  if (!version || !checksumsFile) {
    console.error(
      "usage: bun scripts/homebrew-formula.ts --version <x.y.z> --checksums <checksums.txt>",
    );
    process.exit(2);
  }
  process.stdout.write(formula(version, parseChecksums(readFileSync(checksumsFile, "utf8"))));
}
